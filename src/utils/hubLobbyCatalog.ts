export function filterHubCards(
  cards: HubCardItem[],
  categoryId: string,
  searchQuery: string
): HubCardItem[] {
  const q = searchQuery.trim().toLowerCase();
  return cards.filter((card) => {
    const matchesCat = categoryId === 'all' || card.categoryId === categoryId;
    if (!matchesCat) return false;
    if (!q) return true;
    return (
      card.titleFa.toLowerCase().includes(q) ||
      card.categoryLabelFa.toLowerCase().includes(q) ||
      card.num.toLowerCase().includes(q) ||
      card.keywords.some((k) => k.toLowerCase().includes(q))
    );
  });
}
